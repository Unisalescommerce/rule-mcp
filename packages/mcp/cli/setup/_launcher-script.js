/**
@module cli/setup/launcher-script
 *
 * The text of the global `rule-mcp` launcher.
 *
 * It resolves a target instead of naming one. The copy under the runtime root has
 * no branch, so it answers first; the checkout answers second, so a developer
 * working on the tool still gets their edits live; and when neither answers the
 * launcher exits 127, which means `cannot execute` and nothing else. Exit 1 from
 * node reads exactly like "the validator found violations", which is how a missing
 * entry point once turned a security gate off and looked like a policy decision.
 *
 * @see docs/plans/_stable-launcher-outside-the-checkout.md - Phase 2
 */

/**
 * Render the launcher script.
 *
 * `localBin` is the checkout entry point the install was run from: the fallback,
 * not the target.
 *
 * @param {string} localBin
 * @param {{ root: string }} options - the runtime root, which holds `launcher/current`
 * @returns {string}
 */
export function launcher(localBin, { root }) {
  return [
    "#!/bin/sh",
    "# rule-mcp launcher (generated by the setup wizard)",
    `root=${JSON.stringify(root)}`,
    `checkout=${JSON.stringify(localBin)}`,
    String.raw`version=$(cat "$root/launcher/current" 2>/dev/null | tr -d "\r\n")`,
    'copy="$root/launcher/$version/bin/rule-mcp.js"',
    'if [ -n "$version" ] && [ -f "$copy" ]; then',
    '  exec node "$copy" "$@"',
    "fi",
    'if [ -f "$checkout" ]; then',
    '  exec node "$checkout" "$@"',
    "fi",
    'echo "rule-mcp launcher: cannot start." >&2',
    'echo "  copy:     $copy (from $root/launcher/current)" >&2',
    'echo "  checkout: $checkout" >&2',
    'echo "  neither exists. Run: rule-mcp setup" >&2',
    "exit 127",
    "",
  ].join("\n");
}
