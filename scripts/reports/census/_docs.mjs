/**
 * @module scripts/reports/census/_docs
 *
 * The generated inventories, one per topic.
 *
 * One topic per file keeps a change to the tools out of the history of the
 * personas, and lets the handbook link the inventory a chapter is about. The
 * census writes whole files only: a block fenced inside a chapter a person
 * writes needs an HTML comment, and the documentation holds no HTML.
 */

import { commandSection, hookSection } from "./_sections-agent.mjs";
import { cliSection } from "./_sections-cli.mjs";
import { commandKindsSection } from "./_sections-commands.mjs";
import { envReadersSection } from "./_sections-env.mjs";
import { agentTargetSection } from "./_sections-install.mjs";
import { guardrailSection, personaSection, resourceSection } from "./_sections-quality.mjs";
import { promptSection, skillCatalogSection, summarySection } from "./_sections-surface.mjs";
import { surfaceMapSection } from "./_sections-surface-map.mjs";
import { actionToolSection, skillToolSection } from "./_sections-tools.mjs";

/** Every generated document, in the order the numbers put them. */
const INDEX = [
  ["13-skills.md", "Skills"],
  ["14-tools.md", "Tools"],
  ["15-prompts.md", "Prompts"],
  ["16-instructions.md", "Instructions"],
  ["17-cli.md", "CLI"],
  ["18-personas.md", "Personas"],
  ["19-guardrails.md", "Guardrails"],
  ["20-resources.md", "Resources"],
  ["21-surface-map.md", "Surface map"],
  ["22-install-targets.md", "Install targets"],
  ["23-env-readers.md", "Environment readers"],
];

/**
 * The preamble every generated document carries.
 *
 * @param {string} file - the file being built
 * @param {string} title - its heading
 * @returns {string[]}
 */
function header(file, title) {
  return [`# ${file.slice(0, 2)} - ${title}`, "", "Do not edit this file. `pnpm census` writes it from the live registries.", ""];
}

/** The other inventories, so any one of them is one hop from the rest. */
function footer(file) {
  return ["## Related pages", "", ...INDEX.filter(([name]) => name !== file).map(([name, title]) => `- [${title}](${name})`), ""];
}

/**
 * One document: its file name, and how its body is built from the gathered
 * surface.
 *
 * @param {string} file
 * @param {string} title
 * @param {(data: object) => string[]} body
 * @returns {{file: string, build: (data: object) => string[]}}
 */
const doc = (file, title, body) => ({
  file,
  build: (data) => [...header(file, title), ...body(data), ...footer(file)],
});

/** Every generated document, with the sections its body is assembled from. */
export const GENERATED_DOCS = [
  doc("13-skills.md", "Skills", (data) => skillCatalogSection(data)),
  doc("14-tools.md", "Tools", (data) => [...actionToolSection(data), ...skillToolSection(data)]),
  doc("15-prompts.md", "Prompts", (data) => promptSection(data)),
  doc("16-instructions.md", "Instructions", (data) => [...commandSection(data), ...commandKindsSection(data), ...hookSection()]),
  doc("17-cli.md", "CLI", () => cliSection()),
  doc("18-personas.md", "Personas", (data) => personaSection(data)),
  doc("19-guardrails.md", "Guardrails", (data) => guardrailSection(data)),
  doc("20-resources.md", "Resources", (data) => resourceSection(data)),
  doc("21-surface-map.md", "Surface map", (data) => [...summarySection(data), ...surfaceMapSection(data)]),
  doc("22-install-targets.md", "Install targets", (data) => agentTargetSection(data)),
  doc("23-env-readers.md", "Environment readers", () => envReadersSection()),
];
