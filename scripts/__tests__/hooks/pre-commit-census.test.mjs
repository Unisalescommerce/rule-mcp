/**
The pre-commit census step stages everything it writes.

The hook regenerates the census before every commit and stages what the
generator owns, so a commit ships the documents that match the code. The
snapshot in `scripts/__tests__/fixtures/census.json` is one of those outputs:
it carries a digest per generated document, so it moves whenever a generated
document moves. When the step forgot it, every commit that shifted the snapshot
left the fixture modified and unstaged, and the next `git status` blamed a
clean commit for a dirty tree.

This asserts the list against the snapshot itself rather than against a copy of
it: the fixture already names every document the generator owns, so a document
added later is covered without editing this test.
*/
import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import test from "node:test";

const repo = new URL("../../..", import.meta.url).pathname;
const HOOK = join(repo, ".githooks", "pre-commit");
const SNAPSHOT_PATH = "scripts/__tests__/fixtures/census.json";

/**
 * The paths the hook's `git add` line names, continuations included.
 *
 * @param {string} text
 * @returns {string[]}
 */
function stagedPaths(text) {
  const lines = text.split("\n");
  const start = lines.findIndex((line) => line.startsWith("git add "));

  assert.notEqual(start, -1, "the hook stages what the census writes");

  const paths = [];

  for (const line of lines.slice(start)) {
    const continued = line.trimEnd().endsWith("\\");

    paths.push(
      ...line
        .replace(/\\$/u, "")
        .replace(/^git add /u, "")
        .trim()
        .split(/\s+/u)
        .filter(Boolean),
    );

    if (!continued) {
      break;
    }
  }

  return paths;
}

/** The snapshot's view of the documents the generator owns. */
function ownedDocs() {
  const snapshot = JSON.parse(readFileSync(join(repo, SNAPSHOT_PATH), "utf8"));

  return snapshot.files.map((entry) => `docs/${entry.file}`);
}

test("the census step stages every document the snapshot names", () => {
  const staged = stagedPaths(readFileSync(HOOK, "utf8"));

  for (const doc of ownedDocs()) {
    assert.ok(staged.includes(doc), `${doc} is generated by the census and must be staged by the hook`);
  }
});

test("the census step stages the snapshot it rewrites", () => {
  const staged = stagedPaths(readFileSync(HOOK, "utf8"));

  assert.ok(staged.includes(SNAPSHOT_PATH), `${SNAPSHOT_PATH} is written by the census and must be staged by the hook`);
});
